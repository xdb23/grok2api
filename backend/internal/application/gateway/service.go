// ConfigureSpendingLimitPolicy sets same-account egress rotate count and soft cooldown.
// maxEgressRotations is extra Resin releases after the first 402 (0→default 3, cap 10).
// softCooldown zero → 1h.
func (s *Service) ConfigureSpendingLimitPolicy(maxEgressRotations int, softCooldown time.Duration) {
	if s == nil {
		return
	}
	if maxEgressRotations <= 0 {
		maxEgressRotations = 3
	}
	if maxEgressRotations > 10 {
		maxEgressRotations = 10
	}
	if softCooldown <= 0 {
		softCooldown = time.Hour
	}
	if softCooldown > 72*time.Hour {
		softCooldown = 72 * time.Hour
	}
	s.spendingLimitMaxEgressRotations.Store(int64(maxEgressRotations))
	s.spendingLimitSoftCooldown.Store(int64(softCooldown))
}

func (s *Service) spendingLimitPolicy() (maxRotations int, softCooldown time.Duration) {
	maxRotations = int(s.spendingLimitMaxEgressRotations.Load())
	if maxRotations <= 0 {
		maxRotations = 3
	}
	softCooldown = time.Duration(s.spendingLimitSoftCooldown.Load())
	if softCooldown <= 0 {
		softCooldown = time.Hour
	}
	return maxRotations, softCooldown
}

// UpdateRetryPolicy replaces which upstream HTTP statuses trigger account rotation
// and how many identical non-account failures stop the loop.
// statusCodes nil/empty keeps legacy defaults (402, 403, 429, and all 5xx).
func (s *Service) UpdateRetryPolicy(statusCodes []int, maxSameFingerprint int) {
	if maxSameFingerprint < 1 {
		maxSameFingerprint = 2
	}
	if maxSameFingerprint > 10 {
		maxSameFingerprint = 10
	}
	policy := &retryPolicySnapshot{maxSameFingerprint: maxSameFingerprint, retry5xxWildcard: true}
	if len(statusCodes) > 0 {
		policy.statusCodes = make(map[int]struct{}, len(statusCodes))
		policy.retry5xxWildcard = false
		for _, code := range statusCodes {
			if code < 400 || code > 599 {
				continue
			}
			policy.statusCodes[code] = struct{}{}
			if code >= 500 {
				policy.retry5xxWildcard = true
			}
		}
		if len(policy.statusCodes) == 0 {
			policy.statusCodes = nil
			policy.retry5xxWildcard = true
		}
	}
	s.retryPolicy.Store(policy)
}

func (s *Service) currentRetryPolicy() *retryPolicySnapshot {
	if policy := s.retryPolicy.Load(); policy != nil {
		return policy
	}
	return defaultRetryPolicySnapshot()
}

func (s *Service) statusAllowsRetry(status int) bool {
	policy := s.currentRetryPolicy()
	if policy.statusCodes == nil {
		return isRetryable(status)
	}
	if _, ok := policy.statusCodes[status]; ok {
		return true
	}
	if policy.retry5xxWildcard && status >= 500 {
		return true
	}
	return false
}

// UpdateBuildForbiddenReauthPolicy atomically replaces the Build account invalidation policy.
func (s *Service) UpdateBuildForbiddenReauthPolicy(enabled bool, codes []string) {
	policy := &buildForbiddenReauthPolicy{enabled: enabled, codes: make(map[string]struct{}, len(codes))}
	for _, value := range codes {
		code := strings.ToLower(strings.TrimSpace(value))
		if code != "" {
			policy.codes[code] = struct{}{}
		}
	}
	s.buildForbiddenReauth.Store(policy)
}

func (s *Service) shouldInvalidateBuildForbidden(failure *UpstreamFailure) bool {
	if failure == nil || failure.HTTPStatus != http.StatusForbidden {
		return false
	}
	// Request-level safety / content policy must never trigger account invalidation.
	if failure.RequestScoped {
		return false
	}
	policy := s.buildForbiddenReauth.Load()
	if policy == nil || !policy.enabled {
		return false
	}
	_, matched := policy.codes[strings.ToLower(strings.TrimSpace(failure.UpstreamCode))]
	return matched
}

func (s *Service) markReauthRequired(ctx context.Context, requestID string, credential accountdomain.Credential, reason string) bool {
	writeCtx, cancel := context.WithTimeout(context.WithoutCancel(ctx), accountStateWriteTimeout)
	defer cancel()
	if err := s.accounts.MarkReauthRequired(writeCtx, credential.ID, reason); err != nil {
		s.logger.Error("account_reauth_required_write_failed", "request_id", requestID, "account_id", credential.ID, "provider", credential.Provider, "error", err)
		return false
	}
	s.selector.MarkQuotaStateChanged(credential.Provider)
	return true
}

func teamModelRateLimitKey(providerValue accountdomain.Provider, teamFingerprint, upstreamModel string) string {
	return string(providerValue) + "\x00" + teamFingerprint + "\x00" + strings.TrimSpace(upstreamModel)
}

func rateLimitTeamFingerprint(teamID string) string {
	teamID = strings.TrimSpace(teamID)
	if teamID == "" {
		return ""
	}
	return security.HashToken(teamID)
}

func shortTeamFingerprint(value string) string {
	if len(value) <= 12 {
		return value
	}
	return value[:12]
}

func (s *Service) activeTeamModelRateLimit(credential accountdomain.Credential, upstreamModel string, now time.Time) (teamModelRateLimit, bool) {
	teamFingerprint := rateLimitTeamFingerprint(credential.TeamID)
	s.rateLimitMu.Lock()
	defer s.rateLimitMu.Unlock()
	if teamFingerprint == "" {
		teamFingerprint = s.rateLimitTeams[credential.ID]
	}
	if teamFingerprint == "" {
		return teamModelRateLimit{}, false
	}
	key := teamModelRateLimitKey(credential.Provider, teamFingerprint, upstreamModel)
	value, ok := s.rateLimits[key]
	if !ok {
		return teamModelRateLimit{}, false
	}
	if !now.Before(value.Until) {
		delete(s.rateLimits, key)
		return teamModelRateLimit{}, false
	}
	return value, true
}

func (s *Service) markTeamModelRateLimit(credential accountdomain.Credential, upstreamModel string, metadata provider.RateLimitMetadata, now time.Time) teamModelRateLimit {
	retryAfter := metadata.RetryAfter
	if retryAfter <= 0 {
		retryAfter = time.Minute
	}
	teamFingerprint := rateLimitTeamFingerprint(metadata.TeamID)
	value := teamModelRateLimit{TeamFingerprint: shortTeamFingerprint(teamFingerprint), Until: now.Add(retryAfter)}
	key := teamModelRateLimitKey(credential.Provider, teamFingerprint, upstreamModel)
	until := now.Add(retryAfter)
	s.rateLimitMu.Lock()
	if s.rateLimits == nil {
		s.rateLimits = make(map[string]teamModelRateLimit)
	}
	if s.rateLimitTeams == nil {
		s.rateLimitTeams = make(map[uint64]string)
	}
	s.rateLimitTeams[credential.ID] = teamFingerprint
	for existingKey, value := range s.rateLimits {
		if !now.Before(value.Until) {
			delete(s.rateLimits, existingKey)
		}
	}
	if current, ok := s.rateLimits[key]; ok && !current.Until.Before(until) {
		value = current
	} else {
		s.rateLimits[key] = value
	}
	s.rateLimitMu.Unlock()
	return value
}

// PrewarmSelector loads routing candidates for common routes so the first real
// request after process start does not pay a multi-second SQLite candidate scan.
func (s *Service) PrewarmSelector(ctx context.Context, routes []struct {
	Provider      accountdomain.Provider
	UpstreamModel string
	QuotaMode     string
}) {
	if s == nil || s.selector == nil {
		return
	}
	for _, route := range routes {
		if err := s.selector.Prewarm(ctx, route.Provider, route.UpstreamModel, route.QuotaMode); err != nil {
			if s.logger != nil {
				s.logger.Warn("selector_prewarm_failed", "provider", route.Provider, "upstream_model", route.UpstreamModel, "error", err)
			}
			continue
		}
		if s.logger != nil {
			s.logger.Info("selector_prewarm_ok", "provider", route.Provider, "upstream_model", route.UpstreamModel)
		}
	}
}

